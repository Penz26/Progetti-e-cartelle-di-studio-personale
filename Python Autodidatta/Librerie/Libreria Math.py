import math

pi = 3.14
x = 1
y = 2
z = 3

print(round(pi)) #arrotonda all' intero più vicino
print(math.ceil(pi)) #arrotonda per eccesso
print(math.floor(pi))#arrotonda per difetto
print(abs(pi)) #restituisce il valore assoluto del numero
print(pow(pi,2))#fa una potenza, 1° argomento è la base mentre la 2° è l'esponente
print(math.sqrt(pi)) # fa la radice quadrata
print(max(x, y, z)) #tra i valori passati restituisce il più grande
print(min(x, y, z))#tra i valori passati restituisce il più piccolo